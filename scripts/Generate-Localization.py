"""Generates src/FastTorrentDownload/Services/LocSpanish.cs from Localization/es.txt.

Run after editing es.txt:  python scripts/Generate-Localization.py
The focused checks fail when the generated file is stale or a string has no translation.
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src" / "FastTorrentDownload" / "Services" / "Localization" / "es.txt"
TARGET = ROOT / "src" / "FastTorrentDownload" / "Services" / "LocSpanish.cs"
SEPARATOR = " ⇒ "
BACKSLASH = chr(92)


def literal(text: str) -> str:
    return '"' + text.replace(BACKSLASH, BACKSLASH * 2).replace('"', BACKSLASH + '"') + '"'


def main() -> None:
    entries: list[tuple[str, str]] = []
    keep: list[str] = []
    seen: set[str] = set()
    for number, raw in enumerate(SOURCE.read_text(encoding="utf-8").split("\n"), 1):
        line = raw.rstrip("\r")
        if not line.strip() or line.startswith("#"):
            continue
        if line.startswith("!keep "):
            keep.append(line[len("!keep "):])
            continue
        if SEPARATOR not in line:
            raise SystemExit(f"es.txt:{number}: missing '{SEPARATOR.strip()}' separator")
        key, value = line.split(SEPARATOR, 1)
        if key in seen:
            raise SystemExit(f"es.txt:{number}: duplicate key {key!r}")
        seen.add(key)
        entries.append((key, value))

    lines = [
        "// <auto-generated>",
        "// Generated by scripts/Generate-Localization.py from Services/Localization/es.txt. Do not edit by hand.",
        "// </auto-generated>",
        "namespace FastTorrentDownload.Services;",
        "",
        "public static class LocSpanish",
        "{",
        "    public static IReadOnlyDictionary<string, string> Map { get; } = new Dictionary<string, string>(StringComparer.Ordinal)",
        "    {",
    ]
    lines += [f"        [{literal(key)}] = {literal(value)}," for key, value in entries]
    lines += [
        "    };",
        "",
        "    /// <summary>Texts that are deliberately the same in every language.</summary>",
        "    public static IReadOnlySet<string> Untranslated { get; } = new HashSet<string>(StringComparer.Ordinal)",
        "    {",
    ]
    lines += [f"        {literal(text)}," for text in keep]
    lines += ["    };", "}", ""]
    TARGET.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(entries)} translations, {len(keep)} kept as-is -> {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
